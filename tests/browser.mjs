import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
await mkdir('test-results',{recursive:true});
const browser=await chromium.launch({headless:true, executablePath:process.env.BROWSER_EXECUTABLE||undefined});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/',{waitUntil:'domcontentloaded',timeout:60000});
await page.locator('h1').waitFor({timeout:60000});
await page.screenshot({path:'test-results/desktop.png',fullPage:true});
assert.equal(await page.locator('h1').textContent(),'Find your next feeling.');
assert.ok(await page.locator('svg.lucide').count()>20,'icons are rendered');
await page.getByRole('button',{name:'Play the mix',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('#elapsed').textContent!=='0:00');
assert.equal(await page.locator('#player-title').textContent(),'After Hours');
await page.getByRole('button',{name:'Like current song',exact:true}).click();
assert.ok((await page.locator('#player-like').getAttribute('class')).includes('active'));
await page.locator('.new-playlist').click();
await page.locator('#playlist-form input').fill('Night favorites');
await page.locator('#playlist-form button').click();
await page.locator('.main-nav [data-view="home"]').click();
await page.getByRole('button',{name:'Add After Hours to playlist',exact:true}).click();
await page.locator('[data-save-track]').filter({hasText:'Night favorites'}).click();
await page.locator('.side-playlist').filter({hasText:'Night favorites'}).click();
assert.equal(await page.locator('#main > .track-table .track-row').count(),1);
await page.reload({waitUntil:'domcontentloaded'});
await page.locator('h1').waitFor();
assert.equal(await page.locator('h1').textContent(),'Night favorites');
assert.equal(await page.locator('#main > .track-table .track-row').count(),1);
await page.locator('#search').fill('Ocean');
await page.waitForTimeout(250);
assert.equal(await page.locator('#main > .track-table .track-row').count(),1);
await page.locator('#search').fill('no-such-song-xyz');
await page.waitForTimeout(250);
await page.getByRole('heading',{name:'Your soundtrack starts here'}).waitFor();
await page.locator('#file-input').setInputFiles('public/audio/sun.wav');
await page.waitForFunction(()=>document.querySelector('h1')?.textContent==='Your library');
assert.equal(await page.locator('.track-row').count(),7);
await page.locator('.track-info').filter({hasText:'sun'}).click();
await page.waitForFunction(()=>document.querySelector('#elapsed').textContent!=='0:00');
assert.equal(await page.locator('#player-title').textContent(),'sun');
await page.getByRole('button',{name:'Show queue',exact:true}).click();
assert.equal(await page.locator('.queue-track').count(),7);
await page.getByRole('button',{name:'Close queue',exact:true}).click();
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:5173/#home',{waitUntil:'domcontentloaded'});
await page.locator('.hero').waitFor();
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile page has no horizontal overflow');
await page.screenshot({path:'test-results/mobile.png',fullPage:true});
await page.locator('.mobile-nav [data-view="library"]').click();
assert.equal(await page.locator('h1').textContent(),'Your library');
await page.locator('.track-info').filter({hasText:'sun'}).click();
await page.waitForFunction(()=>document.querySelector('#elapsed').textContent!=='0:00');
assert.deepEqual(errors,[]);
await browser.close();
console.log('Browser checks passed: desktop/mobile layout, playback, favorites, playlist persistence, search, import, and queue.');
