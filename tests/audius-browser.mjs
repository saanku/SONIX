import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
await mkdir('test-results',{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE||undefined,timeout:30000});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 const removedRequests=[];page.on('request',request=>{if(/musicbrainz|releases\.json/i.test(request.url()))removedRequests.push(request.url());});
 await page.route('https://fonts.googleapis.com/**',route=>route.abort());
 await page.goto('http://127.0.0.1:5173/#audius',{waitUntil:'domcontentloaded',timeout:60000});
 await page.locator('#audius-form').waitFor({timeout:60000});
 await page.locator('#audius-form button[type="submit"]:not([disabled])').waitFor({timeout:30000});
 await page.locator('#audius-form input').fill('lofi');
 await page.locator('#audius-form button[type="submit"]').click({timeout:30000});
 await page.getByRole('heading',{name:'Sounds for “lofi”',exact:true}).waitFor();
 await page.locator('#audius-section .track-info').first().waitFor({timeout:35000});
 const first=page.locator('#audius-section .track-row').first();
 const title=await first.locator('.track-info strong').textContent();
 const id=await first.locator('.track-info').getAttribute('data-track');
 await first.locator('.track-info').click();
 await page.waitForFunction(()=>document.querySelector('#elapsed').textContent!=='0:00',{},{timeout:45000});
 assert.equal(await page.locator('#player-title').textContent(),title);
 const duration=await page.locator('#duration').textContent();
 const parts=duration.split(':').map(Number);assert.ok(parts[0]*60+parts[1]>30,'full track exceeds a preview duration');
 await page.locator('#play-toggle').click();
 await page.locator('#player-like').click();
 await page.locator(`#audius-section [data-add="${id}"]`).click();
 await page.locator('[data-action="new-for-track"]').click();
 await page.locator('#playlist-form input').fill('Audius favorites');
 await page.locator('#playlist-form button').click();
 assert.equal(await page.locator('.track-info strong').first().textContent(),title);
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('.track-info').first().waitFor();
 assert.equal(await page.locator('.track-info strong').first().textContent(),title);
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('sonix-library')));
 assert.ok(saved.favorites.includes(id));
 assert.equal(saved.tracks.find(t=>t.id===id).provider,'audius');
 assert.equal(saved.tracks.find(t=>t.id===id).url,undefined);
 await page.locator('.track-info').first().click();
 await page.waitForFunction(()=>document.querySelector('#elapsed').textContent!=='0:00',{},{timeout:45000});
 await page.locator('#play-toggle').click();
 await page.goto('http://127.0.0.1:5173/#home',{waitUntil:'domcontentloaded'});
 await page.locator('.audius-card').first().waitFor({timeout:35000});
 await page.evaluate(async()=>{await Promise.all([...document.querySelectorAll('img:not([loading="lazy"])')].map(img=>Promise.race([img.decode().catch(()=>{}),new Promise(r=>setTimeout(r,5000))])));});
 await page.screenshot({path:'test-results/audius-desktop.png',fullPage:true,timeout:30000});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile layout stays within viewport');
 await page.screenshot({path:'test-results/audius-mobile.png',fullPage:true,timeout:30000});
 await page.goto('http://127.0.0.1:5173/#search',{waitUntil:'domcontentloaded'});
 await page.locator('#audius-form').waitFor();
 assert.equal(await page.locator('#catalog-search').count(),0,'metadata-only search is removed');
 await page.goto('http://127.0.0.1:5173/#discover',{waitUntil:'domcontentloaded'});
 await page.getByRole('heading',{name:'Full songs. Fresh discoveries.'}).waitFor();
 assert.deepEqual(removedRequests,[],'removed integration makes no network requests');
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({result:'passed',title,duration,checks:['live search','full audio playback','favorite persistence','playlist persistence','play after reload','mobile layout','no JavaScript errors']}));
} finally {await browser.close();}
